import re

from research_assist.agents.policies.verification import validate_checks
from research_assist.agents.prompts.writer import INSTRUCTION
from research_assist.domain.coverage import requirements_for
from research_assist.domain.models import (
    Claim,
    ClaimCheck,
    Evidence,
    EvidenceGap,
    ReportBlock,
    ReportSection,
    ResearchRequest,
    WriterOutput,
    WrittenReport,
)
from research_assist.domain.ports import LanguageModel


def escape_markdown(value: str) -> str:
    return re.sub(r"([\\`*_{}\[\]<>()#!|])", r"\\\1", value.replace("\r", " ").replace("\n", " "))


class WriterAgent:
    name = "writer"

    def __init__(self, llm: LanguageModel) -> None:
        self.llm = llm

    async def run(
        self,
        request: ResearchRequest,
        claims: list[Claim],
        checks: list[ClaimCheck],
        evidence: list[Evidence],
        gaps: list[str],
    ) -> tuple[str, str, list[str]]:
        report = await self.compose(request, claims, checks, evidence, gaps)
        return report.title, report.markdown, report.warnings

    async def compose(
        self,
        request: ResearchRequest,
        claims: list[Claim],
        checks: list[ClaimCheck],
        evidence: list[Evidence],
        gaps: list[str],
        gap_details: list[EvidenceGap] | None = None,
        *,
        deterministic: bool = False,
        layout: WriterOutput | None = None,
        user_requirements: list[str] | None = None,
    ) -> WrittenReport:
        checks = validate_checks(claims, evidence, checks)
        supported = {check.claim_id: check for check in checks if check.verdict == "supported"}
        verified = [c for c in claims if c.id in supported]
        en = request.language == "en"
        # The title is user input, never a new factual statement generated by the writer.
        title = " ".join((request.display_question or request.question).split())[:180]
        if not verified:
            message = (
                "I couldn't verify an answer from the passages reviewed in the selected documents."
                if en
                else "Chưa đủ căn cứ từ các đoạn đã đọc để xác nhận câu trả lời."
            )
            directions = self._research_directions(request, gap_details)
            return WrittenReport(
                title=title,
                markdown="\n".join([message, "", *directions]).rstrip() + "\n",
            )
        allowed_topics = {text[:120] for text in (user_requirements or [])}
        local_output = WriterOutput(
            title=title,
            sections=self._sections(verified, request),
        )
        output = (
            layout or local_output
            if deterministic or layout is not None
            else await self.llm.generate(
                task="write_report",
                instruction=(INSTRUCTION),
                payload={
                    "question": request.question,
                    "language": request.language,
                    "style": request.style,
                    "requirements": request.requirements,
                    "verified_claims": [c.model_dump() for c in verified],
                },
                schema=WriterOutput,
                fallback=lambda: local_output,
            )
        )
        lookup = {c.id: c for c in verified}
        ev_lookup = {e.id: e for e in evidence}
        cited: list[str] = []
        used, warnings = set(), []
        headings = {
            "grounded proposals": ("Grounded proposals", "Đề xuất"),
            "methods": ("Methods", "Phương pháp"),
            "results": ("Results", "Kết quả"),
            "comparison": ("Comparison", "So sánh"),
            "limitations": ("Limitations", "Hạn chế"),
        }
        headings.update({pair[1].casefold(): pair for pair in list(headings.values())})
        generic = {
            "answer",
            "evidence",
            "evidence from sources",
            "bằng chứng",
            "bằng chứng từ tài liệu",
        }
        lines: list[str] = []
        selected_ids = {b.claim_id for section in output.sections for b in section.blocks}
        omitted = [c for c in verified if c.id not in selected_ids]
        sections = list(output.sections)
        if omitted:
            sections.append(
                ReportSection(
                    heading="Answer",
                    blocks=[ReportBlock(claim_id=c.id) for c in omitted],
                )
            )
        for section in sections:
            items = []
            for block in section.blocks:
                if block.claim_id not in lookup or block.claim_id in used:
                    if block.claim_id not in lookup:
                        warnings.append(
                            "Writer: đã loại một nhận định chưa được kiểm tra hoặc không tồn tại."
                        )
                    continue
                used.add(block.claim_id)
                claim = lookup[block.claim_id]
                markers = []
                for eid in supported[claim.id].evidence_ids:
                    if eid not in cited:
                        cited.append(eid)
                    markers.append(f"[{cited.index(eid) + 1}]")
                prefix = (
                    ("Proposal: " if en else "Đề xuất: ")
                    if claim.kind == "grounded_recommendation"
                    else ""
                )
                items.append(prefix + escape_markdown(claim.text) + " " + " ".join(markers))
            if items:
                name = section.heading.strip().casefold()
                pair = headings.get(name)
                if pair:
                    lines.extend(["## " + pair[0 if en else 1], ""])
                elif name not in generic:
                    if section.heading in allowed_topics:
                        if name != request.question[:120].strip().casefold():
                            lines.extend(["## " + escape_markdown(section.heading), ""])
                    else:
                        if layout is not None or not deterministic:
                            warnings.append("Writer: đã bỏ tiêu đề mục chưa được xác minh.")
                lines.extend([*([f"- {item}" for item in items] if len(items) > 1 else items), ""])
        if gap_details or gaps:
            # The detailed assessment belongs in structured coverage, not the answer.
            lines += [
                (
                    "The reviewed excerpts leave parts of the question unresolved."
                    if en
                    else "Các đoạn đã đọc chưa đủ để kết luận về mọi phần của câu hỏi."
                ),
                "",
            ]
        lines += self._research_directions(request, gap_details)
        demo = getattr(self.llm, "uses_demo_only", lambda: self.llm.name == "demo")()
        if demo:
            lines.append(
                "*Extractive demo: no LLM or semantic entailment check was used.*"
                if en
                else (
                    "*Chế độ demo trích xuất: không gọi LLM, "
                    "chưa kiểm tra entailment bằng mô hình.*"
                )
            )
            lines.append("")
        lines += ["## " + ("Sources" if en else "Nguồn trích dẫn"), ""]
        for index, eid in enumerate(cited, 1):
            source = ev_lookup[eid]
            locator = (
                (f"p. {source.page}" if en else f"trang {source.page}")
                if source.page is not None
                else source.section
            )
            lines.append(
                f"[{index}] {escape_markdown(source.filename)} — {escape_markdown(locator)} "
                f"— `{source.chunk_id}`\n\n> {escape_markdown(source.quote)}\n"
            )
        return WrittenReport(
            title=title,
            markdown="\n".join(lines) + "\n",
            warnings=list(dict.fromkeys(warnings)),
            claim_ids=[c.id for c in verified if c.id in used],
            citation_evidence_ids=cited,
        )

    @staticmethod
    def _research_directions(request: ResearchRequest, gaps: list[EvidenceGap] | None) -> list[str]:
        if not gaps or (request.style != "literature_review" and request.profile != "academic"):
            return []
        en = request.language == "en"
        requirements = {r.id: r.text for r in requirements_for(request)}
        directions: dict[str, str] = {}
        for gap in gaps:
            rid = gap.requirement_id or ""
            if rid not in requirements or rid in directions:
                continue
            topic = escape_markdown(requirements[rid])
            if gap.reason == "budget_exhausted":
                action = (
                    "Run a focused review with an explicit resource budget for: "
                    if en
                    else "Chạy nghiên cứu tập trung với ngân sách riêng cho: "
                )
            elif gap.reason == "coverage_unassessed":
                action = (
                    "Review the retrieved sources and assess whether they answer: "
                    if en
                    else "Đọc lại nguồn đã truy xuất và đánh giá mức trả lời cho: "
                )
            else:
                action = (
                    "Search arXiv/Crossref for primary studies, import relevant full texts, "
                    "and compare their methods and results for: "
                    if en
                    else "Tìm nghiên cứu gốc trên arXiv/Crossref, bổ sung toàn văn phù hợp "
                    "và đối chiếu phương pháp, kết quả cho: "
                )
            directions[rid] = "- " + action + topic
        if not directions:
            return []
        return [
            "## " + ("Questions for further research" if en else "Hướng tìm hiểu tiếp"),
            "",
            (
                "These suggestions address gaps in this run's retrieved evidence. "
                "Whether a gap exists in the wider literature remains unverified."
                if en
                else "Các gợi ý dựa trên phần bằng chứng còn thiếu trong phiên này. "
                "Chưa xác minh đây có phải khoảng trống của toàn bộ tài liệu nghiên cứu hay không."
            ),
            "",
            *directions.values(),
            "",
        ]

    @staticmethod
    def _sections(claims: list[Claim], request: ResearchRequest) -> list[ReportSection]:
        sections = []
        assigned: set[str] = set()
        for i, requirement in enumerate(request.requirements, 1):
            selected = [
                c for c in claims if f"rq_{i}" in c.requirement_ids and c.id not in assigned
            ]
            if selected:
                sections.append(
                    ReportSection(
                        heading=requirement[:120],
                        blocks=[ReportBlock(claim_id=c.id) for c in selected],
                    )
                )
                assigned.update(c.id for c in selected)
        rest = [c for c in claims if c.id not in assigned]
        if rest:
            sections.append(
                ReportSection(
                    heading="Answer",
                    blocks=[ReportBlock(claim_id=c.id) for c in rest],
                )
            )
        return sections
